namespace Zylance.Core.Platform;

/// <summary>
///     Provides file reference access mode flags for use with file operations.
/// </summary>
public static class FileRefFlags
{
    /// <summary>
    ///     Indicates read-only access to a file reference.
    /// </summary>
    public const bool ReadOnly = true;

    /// <summary>
    ///     Indicates read-write access to a file reference.
    /// </summary>
    public const bool ReadWrite = false;
}
